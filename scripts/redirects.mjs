// Old URLs -> new URLs (301), the one list behind all three server formats in docs/deploy/:
//   .htaccess (Apache), nginx-redirects.conf (nginx), _redirects (Netlify / Cloudflare Pages).
// Run: node scripts/redirects.mjs   (also run by scripts/prerender.mjs, which copies .htaccess and _redirects into dist/).
// Source: docs/CONTENT_PAGE_MAP.md (live pages with no local route) plus retired pages that have a clear new home.
// Other retired pages (demo templates, shop, cart, sample pages) are not redirected: they get the 404 page.
import { mkdirSync, writeFileSync } from 'node:fs'

export const REDIRECTS = [
  ['/case-study/', '/case-studies/'],
  ['/portfolio/', '/case-studies/'],
  ['/author/waseem/', '/blogs/'],
  ['/category/artificial-intelligence/ai-chatbot-development/', '/category/ai-chatbot-development/'],
  ['/category/development/machine-learning-development-service/', '/category/machine-learning-development-service/'],
  ['/agentic-ai-services/', '/ai-agent-development-services/'],
  ['/recommendation-engines/', '/ai-recommendation-systems/'],
  ['/ai4-2026-americas-largest-ai-conference/', '/q2m-solutions-is-heading-to-ai4-2026/'],
]

const head = '# Q2M Solutions: redirects for old URLs (301) and the 404 page. Generated by scripts/redirects.mjs; edit the list there.'
const noSlash = (p) => p.replace(/\/$/, '')
const esc = (p) => noSlash(p).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

const htaccess = [
  head,
  '# Apache: put this file in the web root (next to index.html). Needs mod_rewrite (standard on most hosts).',
  '',
  'ErrorDocument 404 /404.html',
  'DirectoryIndex index.html',
  'Options -Indexes',
  '',
  '<IfModule mod_rewrite.c>',
  'RewriteEngine On',
  '',
  '# Force HTTPS',
  'RewriteCond %{HTTPS} off',
  'RewriteRule ^(.*)$ https://%{HTTP_HOST}/$1 [R=301,L]',
  '',
  '# Use ONE host name. The site uses https://q2msolutions.in (no www): www is redirected to it.',
  'RewriteCond %{HTTP_HOST} ^www\\.q2msolutions\\.in$ [NC]',
  'RewriteRule ^(.*)$ https://q2msolutions.in/$1 [R=301,L]',
  '',
  '# Old URLs',
  ...REDIRECTS.map(([from, to]) => `RewriteRule ^${esc(from).slice(1)}/?$ ${to} [R=301,L]`),
  '</IfModule>',
  '',
  '# Caching: hashed build files and optimised images never change, so they can be cached for a year; pages are always revalidated.',
  '<IfModule mod_headers.c>',
  '  <FilesMatch "\\.(js|css|woff2|avif|webp|png|jpg|svg)$">',
  '    Header set Cache-Control "public, max-age=31536000, immutable"',
  '  </FilesMatch>',
  '  <FilesMatch "\\.html$">',
  '    Header set Cache-Control "no-cache"',
  '  </FilesMatch>',
  '</IfModule>',
  '',
].join('\n')

const nginx = [
  head,
  '# nginx: paste inside the server { } block for q2msolutions.in, with root pointing at the uploaded folder.',
  '# HTTPS and the www -> non-www redirect are set in the server blocks themselves (see docs/DEPLOYMENT_FOR_ADMIN.md).',
  '',
  'index index.html;',
  'error_page 404 /404.html;',
  '',
  '# Old URLs',
  ...REDIRECTS.map(([from, to]) => `location ~ ^${esc(from)}/?$ { return 301 ${to}; }`),
  '',
  '# Pages: /about/ -> /about/index.html; anything else that does not exist -> 404 page',
  'location / { try_files $uri $uri/ =404; }',
  '',
  '# Caching: hashed build files and optimised images for a year; pages always revalidated',
  'location ~* \\.(js|css|woff2|avif|webp|png|jpg|svg)$ { add_header Cache-Control "public, max-age=31536000, immutable"; try_files $uri =404; }',
  'location ~* \\.html$ { add_header Cache-Control "no-cache"; try_files $uri =404; }',
  '',
].join('\n')

const netlify = [
  head,
  '# Netlify / Cloudflare Pages: this file stays in the web root. Both serve 404.html for unknown URLs automatically.',
  '',
  ...REDIRECTS.flatMap(([from, to]) => [`${noSlash(from)}  ${to}  301`, `${from}  ${to}  301`]),
  '',
].join('\n')

export function writeRedirects(dirs = ['docs/deploy']) {
  for (const d of dirs) {
    mkdirSync(d, { recursive: true })
    writeFileSync(`${d}/.htaccess`, htaccess)
    writeFileSync(`${d}/_redirects`, netlify)
    if (d === 'docs/deploy') writeFileSync(`${d}/nginx-redirects.conf`, nginx)
  }
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, '/')}` || process.argv[1]?.endsWith('redirects.mjs')) {
  writeRedirects()
  console.log(`redirects: ${REDIRECTS.length} old URLs -> docs/deploy/.htaccess, nginx-redirects.conf, _redirects`)
}
