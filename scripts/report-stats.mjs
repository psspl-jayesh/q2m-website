// Writes docs/STATS_FOR_APPROVAL.md: every distinct live stat value (value, label, pages) so one value per stat can be approved.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
const log = JSON.parse(readFileSync('docs/_prev/apply-log.json', 'utf8'))
const shared = JSON.parse(readFileSync('src/content/shared/stats.json', 'utf8'))
const live = readdirSync('src/content/live').map((f) => JSON.parse(readFileSync(`src/content/live/${f}`, 'utf8')))
// all stat blocks on the live site (exact), grouped by label
const rows = new Map()
for (const pg of live) for (const b of pg.blocks) if (b.t === 'stat') {
  const label = (b.text || '').replace(/\s+/g, ' ').trim()
  const value = `${b.prefix || ''}${b.value ?? ''}${b.suffix || ''}`
  const k = `${label}|${value}`
  const r = rows.get(k) ?? { label, value, pages: new Set() }
  r.pages.add(pg.path); rows.set(k, r)
}
const shownKeys = new Set(shared.counters.map((c) => c.label.toLowerCase()))
const approved = (r) => /project/i.test(r.label) && r.value.startsWith('150') ? 'shown (shared "150+ Projects Delivered")' : ''
const list = [...rows.values()].sort((a, b) => a.label.localeCompare(b.label) || a.value.localeCompare(b.value))
const byLabel = {}; list.forEach((r) => (byLabel[r.label.toLowerCase()] ??= []).push(r))
const md = ['# Live stat values: please approve one value per stat', '', 'Generated by `scripts/report-stats.mjs` from the exact live content. The live site shows conflicting values for similar stats on different pages. Dropped blocks stay hidden until you approve a value.', '',
  `Distinct (label, value) pairs on the live site: ${list.length}. Stat blocks hidden on our pages: ${log.statsDropped.length}.`, '',
  '## Currently shown (shared stats config, `src/content/shared/stats.json`)', '', '| Value | Label | Source |', '|---|---|---|',
  `| ${shared.projectsDelivered.value}${shared.projectsDelivered.suffix} | ${shared.projectsDelivered.label} | live home hero; also used for every "projects completed/delivered" stat |`,
  ...shared.counters.map((c) => `| ${c.prefix}${c.value}${c.suffix} | ${c.label} | live home counter (data-to-value) |`), '',
  '## All distinct live stats', '', '| Live value | Live label | Pages (count) | Status | Approved value (fill in) |', '|---|---|---|---|---|',
  ...list.map((r) => {
    const status = approved(r) || (shownKeys.has(r.label.toLowerCase().replace(/ across (apac|indian) clients| across apac/, '')) ? 'shown (home counter)' : 'HIDDEN')
    const pages = [...r.pages]
    return `| ${r.value} | ${r.label} | ${pages.slice(0, 3).join(', ')}${pages.length > 3 ? ` +${pages.length - 3} more` : ''} (${pages.length}) | ${status} | |`
  }), '']
writeFileSync('docs/STATS_FOR_APPROVAL.md', md.join('\n')); console.log(list.length, 'distinct;', list.filter((r) => /HIDDEN/.test(approved(r) || '')).length)
