// Step 3: section-by-section comparison, live vs current local content, BEFORE anything is replaced.
// Local = docs/_prev/content.before-live-sync.json (+ home.before-live-sync.json for the home page). Live = src/content/live/*.json.
// Both sides are compared after folding spelling (the local copy was already converted to Indian English).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { fix as spell } from './lib-spelling.mjs'

const prev = JSON.parse(readFileSync('docs/_prev/content.before-live-sync.json', 'utf8'))
const prevHome = JSON.parse(readFileSync('docs/_prev/home.before-live-sync.json', 'utf8'))
const localByPath = new Map([...prev.pages, ...prev.posts, ...prev.caseStudies].map((e) => [e.path, e]))
const live = Object.fromEntries(readdirSync('src/content/live').map((f) => JSON.parse(readFileSync(`src/content/live/${f}`, 'utf8'))).map((p) => [p.path, p]))

const norm = (t) => spell((t || '').normalize('NFKC')).toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' ').trim()
const BODY = new Set(['p', 'li', 'h3', 'h4', 'h5', 'h6', 'stat', 'quote', 'btn'])

/** split a block list into sections at h1/h2; items = comparable text lines */
function sections(blocks, faqs = []) {
  const out = []; let cur = { title: '(intro)', eyebrow: '', items: [] }
  const flush = () => { if (cur.items.length || cur.title !== '(intro)') out.push(cur) }
  for (const b of blocks) {
    if (b.t === 'h1' || b.t === 'h2') { flush(); cur = { title: b.text, eyebrow: b.eyebrow || '', items: [] }; continue }
    if (!BODY.has(b.t)) continue
    cur.items.push({ k: b.t, text: b.t === 'stat' ? `${b.value ?? ''}${b.suffix ?? ''} ${b.text}` : b.t === 'quote' ? b.text : b.text, href: b.href })
  }
  flush()
  if (faqs.length) out.push({ title: 'FAQ', eyebrow: '', items: faqs.flatMap((f) => [{ k: 'q', text: f.q }, ...f.a.map((a) => ({ k: 'a', text: a }))]) })
  return out
}
const isFaqTitle = (t) => /^faq$/i.test(t || '')

const rows = []; const summary = { same: 0, different: 0, missing: 0, extra: 0 }
const md = ['# Content comparison: live site vs current local content (before changes)', '', 'Generated by `scripts/compare-content.mjs`. Spelling is folded on both sides (the local copy was already converted to Indian English), so only real differences show.', '',
  'Status key: **Same** = identical text in the same order; **Different** = heading matches but text differs (counts shown); **Missing locally** = on the live page, not in our content; **Extra locally** = in our content, not on the live page.', '']

for (const [p, lv] of Object.entries(live)) {
  const local = localByPath.get(p)
  let L, localSeo
  if (p === '/') { // local home was built from the Q2M_Website_Home folder
    const h = prevHome
    L = [
      { title: h.hero.lines.map((l) => l.text).join(' '), items: [{ k: 'p', text: h.hero.lead }] },
      { title: h.bts.title, items: h.bts.paras.map((t) => ({ k: 'p', text: t })) },
      { title: h.work.title, items: [...h.work.tiles.map((t) => ({ k: 'p', text: t.title })), { k: 'p', text: h.work.intro }] },
      { title: h.services.title, items: [{ k: 'p', text: h.services.intro }, ...h.services.items.flatMap((s) => [{ k: 'h3', text: s.title }, { k: 'p', text: s.text }, ...s.ticks.map((x) => ({ k: 'li', text: x }))])] },
      { title: h.industries.title, items: [{ k: 'p', text: h.industries.intro }, ...h.industries.items.flatMap((i) => [{ k: 'h3', text: i.name }, { k: 'p', text: i.text }])] },
      { title: h.about.title, items: h.about.paras.map((t) => ({ k: 'p', text: t })) },
      { title: h.team.title, items: [{ k: 'p', text: h.team.intro }] },
      { title: h.approach.title, items: [{ k: 'p', text: h.approach.intro }, ...h.approach.steps.flatMap((s) => [{ k: 'h3', text: s.title }, { k: 'p', text: s.text }])] },
      { title: h.principles.title, items: [{ k: 'p', text: h.principles.intro }, ...h.principles.items.flatMap((i) => [{ k: 'h3', text: i.title }, { k: 'p', text: i.text }])] },
      { title: h.stack.title, items: [{ k: 'p', text: h.stack.intro }, ...h.stack.groups.flatMap((g) => [{ k: 'h3', text: g.title }, { k: 'p', text: g.text }])] },
      { title: h.session.title, items: [{ k: 'p', text: h.session.intro }, ...h.session.steps.flatMap((s) => [{ k: 'h3', text: s.title }, { k: 'p', text: s.text }])] },
      { title: 'FAQ', items: h.faq.items.flatMap((f) => [{ k: 'q', text: f.q }, ...f.a.map((a) => ({ k: 'a', text: a }))]) },
      { title: h.book.title, items: [{ k: 'p', text: h.book.intro }] },
    ]
    localSeo = { title: h.meta.title, description: h.meta.description, h1: h.hero.lines.map((l) => l.text).join(' ') }
  } else if (local) {
    L = sections(local.blocks, local.faqs)
    localSeo = { title: local.metaTitle, description: local.description, h1: local.blocks.find((b) => b.t === 'h1')?.text || local.title }
  } else { L = []; localSeo = {} }
  const V = sections(lv.blocks.filter((b) => !['breadcrumb', 'meta', 'nav'].includes(b.t)), lv.faqs)
  const lmap = new Map(L.map((s) => [isFaqTitle(s.title) ? 'faq' : norm(s.title), s]))
  const vmap = new Map(V.map((s) => [isFaqTitle(s.title) ? 'faq' : norm(s.title), s]))
  const page = { path: p, sections: [], seo: {} }
  for (const f of ['title', 'description', 'h1']) page.seo[f] = norm(lv.seo[f]) === norm(localSeo[f]) ? 'Same' : 'Different'
  for (const [k, vs] of vmap) {
    const ls = lmap.get(k)
    if (!ls) { page.sections.push({ title: vs.title, status: 'Missing locally', detail: `${vs.items.length} items` }); summary.missing++; continue }
    const vi = vs.items.map((i) => norm(i.text)).filter(Boolean), li = ls.items.map((i) => norm(i.text)).filter(Boolean)
    const missing = vi.filter((t) => !li.includes(t)), extra = li.filter((t) => !vi.includes(t))
    const typeMissing = {}; vs.items.forEach((i) => { if (!li.includes(norm(i.text))) typeMissing[i.k] = (typeMissing[i.k] || 0) + 1 })
    const eyebrow = vs.eyebrow ? ` live eyebrow "${vs.eyebrow}" not stored locally;` : ''
    if (!missing.length && !extra.length && !vs.eyebrow) { page.sections.push({ title: vs.title, status: 'Same', detail: `${vi.length} items` }); summary.same++ }
    else { page.sections.push({ title: vs.title, status: 'Different', detail: `${eyebrow}${missing.length ? ` ${missing.length} live item(s) not in local (${Object.entries(typeMissing).map(([a, b]) => b + ' ' + a).join(', ')});` : ''}${extra.length ? ` ${extra.length} local item(s) not on live;` : ''}`.trim(), sample: missing.slice(0, 2) }); summary.different++ }
  }
  for (const [k, ls] of lmap) if (!vmap.has(k)) { page.sections.push({ title: ls.title, status: 'Extra locally', detail: `${ls.items.length} items` }); summary.extra++ }
  page.homoglyphLive = JSON.stringify(lv.blocks).match(/[Ѐ-ӿ]/g)?.length ?? 0
  rows.push(page)
}

md.push('## Summary (sections)', '', `Same: ${summary.same}  |  Different: ${summary.different}  |  Missing locally: ${summary.missing}  |  Extra locally: ${summary.extra}`, '', '## Menu, footer and shared content (live vs local)', '')
const sh = (n) => JSON.parse(readFileSync(`src/content/live-shared/${n}.json`, 'utf8'))
const menu = sh('menu'); const site = readFileSync('src/lib/site.ts', 'utf8')
const localLabels = [...site.matchAll(/label: '([^']+)'/g)].map((m) => m[1])
const liveLabels = menu.flatMap((m) => [m.label, ...m.children.map((c) => c.label)])
md.push(`- Header menu: live has ${liveLabels.length} labels (${menu.filter((m) => m.children.length).length} groups). ${liveLabels.filter((l) => /[Ѐ-ӿ]/.test(l)).length} live labels contain look-alike Cyrillic letters.`, `- Local menu labels that are NOT on the live site (written by us): ${localLabels.filter((l) => !liveLabels.map(norm).includes(norm(l))).join('; ')}`, `- Live menu labels missing locally: ${liveLabels.filter((l) => !localLabels.map(norm).includes(norm(l)) && l).join('; ')}`, `- Live menu items linking to "#": ${menu.flatMap((m) => m.children.filter((c) => c.href === '#').map((c) => `${m.label} > ${c.label}`)).length}`, '')
md.push('## Per page', '')
for (const r of rows.sort((a, b) => a.path.localeCompare(b.path))) {
  md.push(`### ${r.path}`, `SEO: title ${r.seo.title}, description ${r.seo.description}, H1 ${r.seo.h1}${r.homoglyphLive ? `  |  non-Latin look-alike characters in live text: ${r.homoglyphLive}` : ''}`, '', '| Section | Status | Detail |', '|---|---|---|')
  for (const s of r.sections) md.push(`| ${s.title.slice(0, 70).replace(/\|/g, '/')} | ${s.status} | ${s.detail.replace(/\|/g, '/')} |`)
  md.push('')
}
writeFileSync('docs/CONTENT_COMPARISON.md', md.join('\n'))
writeFileSync('docs/_prev/comparison.json', JSON.stringify({ summary, rows }))
console.log(summary, 'pages', rows.length)
