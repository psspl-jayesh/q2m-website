// Final consistency check: final content (src/content/pages) vs exact live content (src/content/live).
// Every difference must be explained by: locale spelling, Cyrillic fix, typo fix, India override, or a logged drop.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fix as spell } from './lib-spelling.mjs'

const HOMO = { 'е': 'e', 'а': 'a', 'о': 'o', 'с': 'c', 'р': 'p', 'х': 'x', 'і': 'i' }
const log = JSON.parse(readFileSync('docs/_prev/apply-log.json', 'utf8'))
const live = Object.fromEntries(readdirSync('src/content/live').map((f) => JSON.parse(readFileSync(`src/content/live/${f}`, 'utf8'))).map((p) => [p.slug, p]))
const fin = Object.fromEntries(readdirSync('src/content/pages').filter((f) => f.endsWith('.json')).map((f) => JSON.parse(readFileSync(`src/content/pages/${f}`, 'utf8'))).map((p) => [p.slug, p]))
const overrideAfters = log.overrides.map((o) => o.after)
const typoAfters = log.typos.map((t) => t.after)
const tok = (t) => (t || '').split(/(\s+)/)
const toLatin = (t) => t.replace(/[Ѐ-ӿ]/g, (c) => HOMO[c] ?? c)

/** Is `final` explained by `liveText` + the allowed transformations? */
function explained(liveText, finalText) {
  if (liveText === finalText) return 'identical'
  const l1 = toLatin(liveText)
  if (spell(l1) === finalText || l1 === finalText) return 'cyrillic/spelling'
  if (overrideAfters.some((a) => finalText.includes(a))) return 'india override'
  if (typoAfters.some((a) => finalText.includes(a))) return 'typo fix'
  // tolerate combinations: compare after folding spelling on both sides
  if (spell(toLatin(liveText)).replace(/[’']/g, "'") === spell(finalText).replace(/[’']/g, "'")) return 'spelling+contraction'
  // token-level: every differing token is a spelling/cyrillic/typo/contraction variant
  const a = tok(spell(l1)), b = tok(finalText)
  if (a.length === b.length && a.every((t, i) => t === b[i] || spell(t) === b[i] || /^[’'a-z]{2,6}$/i.test(t) && b[i].replace(/[’']/g, '') === t.replace(/[’']/g, ''))) return 'spelling+contraction'
  return null
}

const rows = []; let unexplainedTotal = 0
const sameKinds = {}
for (const slug of Object.keys(fin)) {
  const L = live[slug].blocks.filter((b) => !['breadcrumb', 'meta', 'nav'].includes(b.t))
  const F = fin[slug].blocks
  let j = 0; let identical = 0, changed = 0; const unexplained = []; const dropped = []
  for (const fb of F) {
    // find the corresponding live block, in order
    let k = j, found = -1
    for (; k < L.length; k++) { if (L[k].t === fb.t || (L[k].t === 'h2' && fb.t === 'h1') || (L[k].t === 'stat' && fb.t === 'stat')) { if ((L[k].text ?? '') === '' && (fb.text ?? '') === '') { found = k; break } const e = explained(L[k].text ?? '', fb.text ?? ''); if (e || fb.t === 'stat') { found = k; break } } }
    if (found < 0) { unexplained.push(`${fb.t}: ${(fb.text || '').slice(0, 70)}`); continue }
    for (let d = j; d < found; d++) dropped.push(`${L[d].t}: ${(L[d].text || '').slice(0, 50)}`)
    const e = fb.t === 'stat' ? 'identical' : explained(L[found].text ?? '', fb.text ?? '')
    if (e === 'identical') identical++; else { changed++; sameKinds[e] = (sameKinds[e] || 0) + 1 }
    j = found + 1
  }
  for (let d = j; d < L.length; d++) dropped.push(`${L[d].t}: ${(L[d].text || '').slice(0, 50)}`)
  // SEO
  const h1Logged = log.h1.some((x) => x.path === fin[slug].path)
  const seoDiff = ['title', 'description', 'h1'].filter((f) => !(f === 'h1' && h1Logged) && explained(live[slug].seo[f] ?? '', fin[slug].seo[f] ?? '') === null)
  // FAQs
  const faqDiff = fin[slug].faqs.filter((f, i) => explained(live[slug].faqs[i]?.q ?? '', f.q) === null || f.a.some((a, x) => explained(live[slug].faqs[i]?.a[x] ?? '', a) === null)).length
  unexplainedTotal += unexplained.length + seoDiff.length + faqDiff
  rows.push({ slug, live: L.length, final: F.length, identical, changed, dropped: dropped.length, droppedList: dropped, unexplained, seoDiff, faqDiff })
}
const md = ['# Final consistency check: live vs local content', '', 'Generated by `scripts/verify-content.mjs`. Every final block is aligned with its live block and the difference (if any) must be explained by a logged change.', '',
  `Pages checked: ${rows.length}. Blocks identical to live: ${rows.reduce((a, r) => a + r.identical, 0)}. Blocks changed only by the listed fixes/overrides/spelling: ${rows.reduce((a, r) => a + r.changed, 0)} (${Object.entries(sameKinds).map(([k, v]) => `${k}: ${v}`).join(', ')}). **Unexplained differences: ${unexplainedTotal}.**`, '',
  '| Page | Live blocks | Local blocks | Identical | Changed (explained) | Not shown (see CONTENT_CHANGES) | Unexplained |', '|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.slug} | ${r.live} | ${r.final} | ${r.identical} | ${r.changed} | ${r.dropped} | ${r.unexplained.length + r.seoDiff.length + r.faqDiff} |`), '']
const bad = rows.filter((r) => r.unexplained.length || r.seoDiff.length || r.faqDiff)
if (bad.length) { md.push('## Unexplained differences', ''); bad.forEach((r) => { md.push(`### ${r.slug}`); r.unexplained.forEach((u) => md.push('- block: ' + u)); r.seoDiff.forEach((u) => md.push('- seo: ' + u)); if (r.faqDiff) md.push(`- faq entries differing: ${r.faqDiff}`) }) }
const droppedAll = {}; rows.forEach((r) => r.droppedList.forEach((d) => { const k = d.split(':')[0] + ': ' + d.split(':').slice(1).join(':').trim().slice(0, 40); droppedAll[k] = (droppedAll[k] || 0) + 1 }))
md.push('', '## Live blocks not carried over (grouped)', '', ...Object.entries(droppedAll).sort((a, b) => b[1] - a[1]).slice(0, 40).map(([k, v]) => `- ${k} (${v})`))
writeFileSync('docs/CONTENT_VERIFICATION.md', md.join('\n') + '\n')
console.log('pages', rows.length, 'unexplained', unexplainedTotal, 'identical', rows.reduce((a, r) => a + r.identical, 0), 'changed', rows.reduce((a, r) => a + r.changed, 0))
bad.slice(0, 8).forEach((r) => console.log(r.slug, r.unexplained.slice(0, 2), r.seoDiff, r.faqDiff))
